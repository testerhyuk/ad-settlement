create table advertisement(
    advertisement_id bigint generated by default as IDENTITY primary key,
    advertiser_id bigint not null references advertiser(advertiser_id),
    advertisement_name varchar(100) not null,
    budget_amount numeric(19, 2) not null,
    impression_price numeric(19, 2) not null,
    conversion_price numeric(19, 2) not null,
    status varchar(20) not null check(status in ('ACTIVE', 'PAUSED', 'ENDED', 'SCHEDULED')),
    created_at timestamptz not null,
    started_at timestamptz not null,
    expired_at timestamptz not null
)