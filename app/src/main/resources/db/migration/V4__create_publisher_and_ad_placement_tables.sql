create table publisher(
    publisher_id bigint generated by default as IDENTITY primary key,
    publisher_name varchar(100) not null,
    site_url varchar(255) not null unique,
    created_at timestamptz not null
);

create table ad_placement(
    placement_id bigint generated by default as IDENTITY primary key,
    publisher_id bigint not null references publisher(publisher_id),
    placement_name varchar(100) not null,
    status varchar(10) not null check (status in ('ACTIVE', 'INACTIVE')),
    created_at timestamptz not null,

    -- 동일한 퍼블리셔 내에서 광고 지면 이름 중복 등록 방지
    CONSTRAINT uk_ad_placement_publisher_name
        UNIQUE (publisher_id, placement_name)
);